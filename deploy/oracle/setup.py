#!/usr/bin/env python3
"""Prepare this Oracle deployment without pulling images or starting services."""
from pathlib import Path
import json
import os
import secrets

root = Path(__file__).resolve().parents[2]
spec = json.loads(Path(__file__).with_name('deployment.json').read_text())
name = spec['name']
target = '/opt/safrano9999/' + root.name
def write_new(path, text, mode=0o644):
    try: fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, mode)
    except FileExistsError: return
    with os.fdopen(fd, 'w') as stream: stream.write(text)

write_new(root / 'config.conf', '\n'.join(k+'='+v for k,v in spec['config'].items())+'\n')
env = spec['env'].copy()
if name == 'naturalgrounding':
    env['NATURALGROUNDING_DJANGO_SECRET_KEY'] = secrets.token_urlsafe(64)
    env['NATURALGROUNDING_ADMIN_PASSWORD'] = secrets.token_urlsafe(32)
write_new(root / '.env', '# Provider keys can be added later; existing secrets are preserved.\n'+'\n'.join(k+'='+v for k,v in env.items())+'\n', 0o600)
write_new(root / 'container.conf', 'IMAGE=ghcr.io/safrano9999/'+spec['image']+':latest\nNETWORK=litellm-free_default\nCADDY_PORT='+str(spec['port'])+'\n')
for directory in spec['dirs']: (root / directory).mkdir(exist_ok=True)
quadlet = [
    '# Generated by deploy/oracle/setup.py from deployment.json',
    '[Unit]', 'Description='+root.name+' on Oracle', '',
    '[Container]', 'ContainerName='+name,
    'Image=ghcr.io/safrano9999/'+spec['image']+':latest',
    'Pull=never', 'Network=litellm-free_default',
    'UserNS=keep-id:uid=1000,gid=1000', 'User=1000', 'Group=1000',
    'NoNewPrivileges=true', 'DropCapability=all',
    'EnvironmentFile='+str(root/'config.conf'), 'EnvironmentFile='+str(root/'.env'),
]
for directory in spec['dirs']: quadlet.append('Volume='+str(root/directory)+':'+target+'/'+directory+':rw')
quadlet += ['', '[Service]', 'Restart=on-failure', 'RestartSec=10', 'TimeoutStartSec=300', '', '[Install]', 'WantedBy=default.target', '']
path = root / (name+'.container')
path.write_text('\n'.join(quadlet))
links = Path.home()/'.config/containers/systemd'
links.mkdir(parents=True, exist_ok=True)
link = links/path.name
if link.is_symlink():
    if link.resolve() != path: raise SystemExit('Existing link belongs to another deployment: '+str(link))
elif link.exists(): raise SystemExit('Existing unit is not a symlink: '+str(link))
else: link.symlink_to(path)
print(str(link)+' -> '+str(path))
